"""Run all five Lab 7 bonuses in a disposable source copy and database.
From API root: DATABASE_URL=.../lab7_bonus_20261112 python experiments/run_bonus.py
"""
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

import psycopg
from sqlalchemy.engine import make_url

source = Path(__file__).resolve().parents[1]
url = make_url(os.environ['DATABASE_URL'])
if url.database != 'lab7_bonus_20261112':
    raise SystemExit('Use only the dedicated lab7_bonus_20261112 database')
artifacts = source / 'experiments' / 'bonus_artifacts'
artifacts.mkdir(exist_ok=True)
connection = psycopg.connect(host=url.host, port=url.port, user=url.username,
    password=url.password, dbname=url.database, autocommit=True)

def sql(statement, error=None):
    print('SQL:', statement, flush=True)
    try:
        with connection.cursor() as cursor:
            cursor.execute(statement)
            rows = cursor.fetchall() if cursor.description else None
            if rows is not None:
                print(rows, flush=True)
    except psycopg.Error as exc:
        print(type(exc).__name__, exc.sqlstate, str(exc), flush=True)
        if error is None or not isinstance(exc, error):
            raise
        return None
    if error is not None:
        raise AssertionError('Expected SQL error was not raised')
    return rows

def run(*args, ok=True):
    print('$', ' '.join(args), flush=True)
    result = subprocess.run(args, cwd=project, env={**os.environ, 'PYTHONDONTWRITEBYTECODE': '1'},
        stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=180)
    print(result.stdout, flush=True)
    assert (result.returncode == 0) == ok, (args, result.returncode)
    return result.stdout

def alembic(*args, **kwargs):
    return run(sys.executable, '-m', 'alembic', *args, **kwargs)

def seed():
    sql((project / 'seed.sql').read_text())

def save(name, value):
    (artifacts / name).write_text(value)

def migration(body):
    return '''from alembic import op
import sqlalchemy as sa
revision = "0003"
down_revision = "0002"
branch_labels = None
depends_on = None
''' + body

try:
    with tempfile.TemporaryDirectory(prefix='lab7-bonus-') as folder:
        project = Path(folder) / 'api'
        shutil.copytree(source, project,
            ignore=shutil.ignore_patterns('.git', '.venv', '__pycache__', 'experiments', '.env'))
        model = project / 'models.py'
        original = model.read_text()
        # The explicitly named disposable database is the only schema reset here.
        sql('DROP SCHEMA public CASCADE; CREATE SCHEMA public')
        alembic('upgrade', 'head')
        seed()

        print('\nBONUS 1: CHECK autogenerate and op.f', flush=True)
        model.write_text(original.replace('CheckConstraint("credits > 0", name="credits"),',
            'CheckConstraint("credits > 0", name="credits"),\n                      CheckConstraint("level IN (\'beginner\', \'intermediate\', \'advanced\')", name="level"),'))
        alembic('check')
        alembic('revision', '--autogenerate', '-m', 'level check', '--rev-id', '0003')
        file = next((project / 'alembic/versions').glob('0003_*.py'))
        generated = file.read_text()
        print(generated, flush=True)
        assert '    pass' in generated and 'create_check_constraint' not in generated
        save('01_check_autogenerated.py.txt', generated)
        file.unlink()
        alembic('revision', '-m', 'level check', '--rev-id', '0003')
        file = next((project / 'alembic/versions').glob('0003_*.py'))
        broken = migration('''
def upgrade():
    op.create_check_constraint(op.f("courses_level_check"), "courses",
                               "level IN ('beginner', 'intermediate', 'advanced')")
def downgrade():
    op.drop_constraint("courses_level_check", "courses", type_="check")
''')
        file.write_text(broken)
        save('01_check_broken_downgrade.py.txt', broken)
        alembic('upgrade', 'head')
        sql("UPDATE courses SET level='expert' WHERE id='api-design'", error=psycopg.errors.CheckViolation)
        failed = alembic('downgrade', '-1', ok=False)
        assert 'courses_courses_level_check_check' in failed
        assert '0003' in alembic('current')
        fixed = broken.replace('op.drop_constraint("courses_level_check",',
            'op.drop_constraint(op.f("courses_level_check"),')
        file.write_text(fixed)
        save('01_check_fixed.py.txt', fixed)
        alembic('downgrade', '-1')
        file.unlink()
        model.write_text(original)
        alembic('check')

        print('\nBONUS 2: rename description without losing data', flush=True)
        seed()
        descriptions = sql('SELECT id, description FROM courses ORDER BY id')
        model.write_text(original.replace('    description: Mapped[str]', '    summary: Mapped[str]'))
        alembic('revision', '--autogenerate', '-m', 'rename description', '--rev-id', '0003')
        file = next((project / 'alembic/versions').glob('0003_*.py'))
        generated = file.read_text()
        print(generated, flush=True)
        assert 'add_column' in generated and 'drop_column' in generated
        save('02_rename_autogenerated.py.txt', generated)
        fixed = migration('''
def upgrade():
    op.alter_column("courses", "description", new_column_name="summary")
def downgrade():
    op.alter_column("courses", "summary", new_column_name="description")
''')
        file.write_text(fixed)
        save('02_rename_fixed.py.txt', fixed)
        alembic('upgrade', 'head')
        alembic('check')
        assert sql('SELECT id, summary FROM courses ORDER BY id') == descriptions
        print('All six descriptions preserved after rename: PASS', flush=True)
        alembic('downgrade', '-1')
        assert sql('SELECT id, description FROM courses ORDER BY id') == descriptions
        file.unlink()
        model.write_text(original)
        alembic('check')

        print('\nBONUS 3: N+1 queries', flush=True)
        seed()
        output = run(sys.executable, 'try_n_plus_1.py')
        assert 'queries: 7' in output and 'queries: 2' in output

        print('\nBONUS 4: lost update versus atomic expression', flush=True)
        seed()
        run(sys.executable, 'try_lost_update.py')
        seed()
        run(sys.executable, 'try_lost_update.py', '--atomic')
        seed()

        print('\nBONUS 5: passive_deletes and database CASCADE', flush=True)
        model.write_text(original.replace('back_populates="student", passive_deletes=True',
            'back_populates="student"'))
        output = run(sys.executable, 'try_delete.py', ok=False)
        assert 'NotNullViolation' in output and 'student_id' in output
        assert sql('SELECT (SELECT count(*) FROM students), (SELECT count(*) FROM enrollments)') == [(3, 6)]
        model.write_text(original)
        run(sys.executable, 'try_delete.py')
        assert sql('SELECT (SELECT count(*) FROM students), (SELECT count(*) FROM enrollments)') == [(2, 5)]
        seed()

        print('\nFINAL RESTORATION', flush=True)
        assert model.read_text() == original
        assert len(list((project / 'alembic/versions').glob('*.py'))) == 2
        alembic('current')
        alembic('heads')
        alembic('check')
        run(sys.executable, 'check_models.py')
        run(sys.executable, '-m', 'unittest', '-v')
        assert sql('SELECT (SELECT count(*) FROM courses), (SELECT count(*) FROM students), (SELECT count(*) FROM enrollments)') == [(6, 3, 6)]
        print('ALL FIVE BONUSES PASSED; models, migrations and seed restored', flush=True)
finally:
    connection.close()
